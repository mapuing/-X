def _out(text, *streams):
    """터미널 + 파일 버퍼에 동시 출력."""
    for s in streams:
        s.write(text + "\n")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    random.seed()

    # 파일 저장용 버퍼
    buf = io.StringIO()
    out = lambda text="": _out(text, sys.stdout, buf)

    out("=" * 80)
    out("마푸잉 트윗 주제 생성기 v2.6")
    out("소재+공식 동적 조합 (9,900+ 주제)")
    out("=" * 80)

    # 1. 주제 뽑기
    recommender = TopicRecommender()
    topics = recommender.recommend(20)

    out()
    out("=" * 80)
    out("🎰 주제 뽑기 결과 (20개)")
    out("=" * 80)
    out()
    out(f" {'#':>2} | {'유형':^12} | {'서브타입':^16} | 주제")
    out(f" {'─'*2} | {'─'*12} | {'─'*16} | {'─'*40}")

    for t in topics:
        out(f" {t['rank']:>2} | [{t['type_code']}] {t['type']:<7} | {t['subtype']:<16} | {t['topic']}")

    out()

    # 유형별 반응 요약
    seen = {}
    for t in topics:
        if t['type'] not in seen:
            seen[t['type']] = t['reaction']
    reactions = " / ".join(f"{k}→{v}" for k, v in seen.items())
    out(f"유형별 반응: {reactions}")
    out()

    # 유형별 분포 요약
    type_counts = defaultdict(int)
    for t in topics:
        type_counts[t['type']] += 1
    dist = " / ".join(f"{k} {v}개" for k, v in type_counts.items())
    out(f"유형별 분포: {dist}")
    out()

    out("=" * 80)
    out("사용법: 위 주제 중 마음에 드는 것을 골라 서칭으로 Hook/Body를 채우세요.")
