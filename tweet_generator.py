# 핵심 소재 — 같은 배치 내 중복 차단 (겹치면 반복감)
_CORE_INGREDIENTS = {
    "신체부위", "기기앱", "대상", "에티켓상황", "대화상황",
    "심리상태", "상식주제", "논쟁주제", "분노상황", "스토리상황",
    "대비쌍", "딜레마", "개방질문", "업계", "의외특성A",
    "권위자",
}

# 쌍(tuple) 소재를 개별 키로 매핑
_PAIR_MAP = {
    "대비A": ("대비쌍", 0),
    "대비B": ("대비쌍", 1),
    "딜레마A": ("딜레마", 0),
    "딜레마B": ("딜레마", 1),
}

# 한국어 조사 매핑 (받침 있을 때, 받침 없을 때)
_PARTICLES = {
    "이": ("이", "가"),
    "을": ("을", "를"),
    "은": ("은", "는"),
    "와": ("과", "와"),
    "이라면": ("이라면", "라면"),
    "으로": ("으로", "로"),
}


def _has_batchim(char):
    """한글 문자에 받침(종성)이 있는지 확인."""
    if '가' <= char <= '힣':
        return (ord(char) - 0xAC00) % 28 > 0
    return True  # 비한글(숫자, 영어 등)은 받침 있는 것으로 처리


def _apply_particle(word, particle_key):
    """단어 뒤에 받침에 맞는 조사를 붙여 반환."""
    forms = _PARTICLES.get(particle_key)
    if not forms or not word:
        return word + particle_key
    consonant_form, vowel_form = forms
    return word + (consonant_form if _has_batchim(word[-1]) else vowel_form)


def _render_formula(template):
    """템플릿의 {placeholder}를 INGREDIENTS에서 랜덤 선택하여 채움.

    지원 문법:
    - {키}        → INGREDIENTS[키]에서 랜덤 선택
    - {키#조사}   → 랜덤 선택 후 한국어 조사 자동 처리 (이/가, 을/를 등)

    Returns:
        (rendered_string, picked_dict) — picked_dict는 {소재통이름: 선택된값} 매핑
    """
    keys = set(re.findall(r"\{(.+?)\}", template))
    values = {}
    picked = {}

    # 쌍 소재 먼저 해결 (같은 쌍에서 A, B를 가져와야 하므로)
    resolved_pairs = {}
    for key in keys:
        # 조사 분리: {대상#이} → ing_key="대상", particle="이"
        if "#" in key:
            ing_key, particle = key.split("#", 1)
        else:
            ing_key, particle = key, None

        # 소재 값 결정
        if ing_key in _PAIR_MAP:
            pool_name, idx = _PAIR_MAP[ing_key]
            if pool_name not in resolved_pairs:
                resolved_pairs[pool_name] = random.choice(INGREDIENTS[pool_name])
            raw_value = resolved_pairs[pool_name][idx]
            picked[pool_name] = resolved_pairs[pool_name]
        elif ing_key in INGREDIENTS:
            raw_value = random.choice(INGREDIENTS[ing_key])
            picked[ing_key] = raw_value
        else:
            continue

        # 조사 적용
        values[key] = _apply_particle(raw_value, particle) if particle else raw_value

    try:
        return template.format(**values), picked
    except KeyError:
        return template, picked


def _render_hybrid(type_name):
    """type_name에 맞는 하이브리드 공식을 렌더링. (topic, subtype, picked) 반환."""
    matching = [h for h in HYBRID_FORMULAS if h["parent_type"] == type_name]
    if not matching:
        return None, None, {}
    hybrid = random.choice(matching)
    topic, picked = _render_formula(hybrid["formula"])
    return topic, hybrid["subtype"], picked


def _has_ingredient_conflict(picked, used_ingredients):
    """picked 소재 중 핵심 소재가 이미 사용되었는지 확인."""
    for pool_name, value in picked.items():
        if pool_name in _CORE_INGREDIENTS and value in used_ingredients[pool_name]:
            return True
    return False


def _pick_proven(type_name):
    """검증된 주제에서 랜덤 하나. (topic, subtype) 반환."""
    type_topics = PROVEN_TOPICS.get(type_name, {})
    if not type_topics:
        return None, None
    subtype_name = random.choice(list(type_topics.keys()))
    topics = type_topics[subtype_name]
    if not topics:
        return None, None
    return random.choice(topics), subtype_name


def _maybe_frame(topic, type_name):
    """50% 확률로 유형에 맞는 프레이밍 접두사 추가."""
    if random.random() > 0.5:
        return topic
    framing_types = TYPE_FRAMINGS.get(type_name, [])
    if not framing_types:
        return topic
    framing_type = random.choice(framing_types)
    prefixes = FRAMINGS.get(framing_type, [])
    if not prefixes:
        return topic
    return random.choice(prefixes) + topic


