class TopicRecommender:
    """소재+공식 조합 기반 동적 주제 생성기."""

    def __init__(self):
        pass

    def recommend(self, count=20):
        """count개 주제를 7유형에서 골고루 뽑아 반환."""
        results = []
        used_topics = set()
        used_ingredients = defaultdict(set)  # {소재통이름: {사용된값들}}
        used_subtypes = defaultdict(lambda: defaultdict(int))  # {유형: {서브타입: 횟수}}

        distribution = SLOT_DISTRIBUTION[:count]

        for type_name in distribution:
            type_info = TYPE_INFO.get(type_name)
            if not type_info:
                continue

            # 가장 적게 사용된 서브타입 우선 선택
            subtypes = type_info["subtypes"]
            sub_counts = used_subtypes[type_name]
            min_count = min(sub_counts.get(s, 0) for s in subtypes)
            candidates = [s for s in subtypes if sub_counts.get(s, 0) == min_count]
            subtype_name = random.choice(candidates)
            topic_text = None
            topic_picked = {}

            for _attempt in range(10):
                roll = random.random()

                if roll < 0.8:
                    # 80%: 공식 기반 생성
                    formulas = FORMULAS.get(subtype_name, [])
                    if formulas:
                        template = random.choice(formulas)
                        candidate, picked = _render_formula(template)
                    else:
                        continue
                elif roll < 0.9:
                    # 10%: 하이브리드
                    candidate, hybrid_sub, picked = _render_hybrid(type_name)
                    if candidate:
                        subtype_name = hybrid_sub
                    else:
                        continue
                else:
                    # 10%: 검증된 주제
                    candidate, proven_sub = _pick_proven(type_name)
                    picked = {}
                    if candidate:
                        subtype_name = proven_sub
                    else:
                        continue

                if candidate and candidate not in used_topics:
                    if not _has_ingredient_conflict(picked, used_ingredients):
                        topic_text = candidate
                        topic_picked = picked
                        break

            # 폴백: 공식 기반 재시도
            if not topic_text:
                for sub in type_info["subtypes"]:
                    formulas = FORMULAS.get(sub, [])
                    if not formulas:
                        continue
                    for _ in range(5):
                        template = random.choice(formulas)
                        candidate, picked = _render_formula(template)
                        if candidate not in used_topics:
                            if not _has_ingredient_conflict(picked, used_ingredients):
                                topic_text = candidate
                                topic_picked = picked
                                subtype_name = sub
                                break
                    if topic_text:
                        break

            if topic_text:
                used_topics.add(topic_text)
                for pool_name, value in topic_picked.items():
                    if pool_name in _CORE_INGREDIENTS:
                        used_ingredients[pool_name].add(value)
                used_subtypes[type_name][subtype_name] += 1
                display_topic = _maybe_frame(topic_text, type_name)

                results.append({
                    "rank": len(results) + 1,
                    "type": type_name,
                    "type_code": type_info["code"],
                    "subtype": subtype_name,
                    "topic": display_topic,
                    "reaction": type_info["reaction"],
                })

        return results


